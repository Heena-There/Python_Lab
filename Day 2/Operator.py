#Arithmetic Operator(+-/*//%)
a=10
b=3
print(a+b)
print(a-b)
print(a*b)
print(round((a/b),2))
print(a//b)
print(a%b)

#Relational Operator(<,>,<=,>=,==,!=)
print(a<b)
print(a>b)
print(a>=b)
print(a<=b)
print(a==b)
print(a!=b)

#logical Operator(and,or,not)
print(1 and 0)
print(1 and 1)
print(1 or 0)
print(not 1)
print(not 0)

#Bitwise Operator(& | ^ ~ >> <<)
print(a & b)
print(a | b)
print(a ^ b)
print(~b)
print(4 >> 2)
print(5 << 2)

#assignment operator(-=,/=,+=,%=,*=)
a+=b
print(a)
a/=2
print(a)

#Membership Operator(in,not in)
print('D' in 'Delhi')
print('D' not in 'Delhi')
print(1 in [2,3,4,5,6])
print(6 in [2,3,4,5,6])
